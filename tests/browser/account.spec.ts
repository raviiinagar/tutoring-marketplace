import {test,expect} from '@playwright/test';
const browserOrigin=process.env.PLAYWRIGHT_BASE_URL||'http://localhost:3100';
const aliasOrigin=new URL(browserOrigin);aliasOrigin.hostname=new URL(browserOrigin).hostname==='localhost'?'127.0.0.1':'localhost';
for(const origin of [browserOrigin,aliasOrigin.origin])test(`Lovable account journey from ${origin}`,async({page})=>{
  test.setTimeout(120_000);
  const email=`browser-${Date.now()}@example.test`;
  await page.goto(origin+'/auth/signup');
  await page.getByLabel('Your name').fill('Browser Learner');
  await page.getByLabel('Email',{exact:true}).fill(email);
  await page.getByLabel('Password').fill('Browser-password-321!');
  const registration=page.waitForResponse(r=>r.url().endsWith('/v1/auth/registrations')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Create account',exact:true}).click();
  expect((await registration).status()).toBe(202);
  await expect(page).toHaveURL(/check-email/);
  await page.getByRole('link',{name:'Open captured email inbox'}).click();
  const message=page.getByRole('listitem').filter({hasText:email});
  await message.getByRole('link',{name:'Open verification link'}).click();
  await expect(page.getByRole('button',{name:'Verify email',exact:true})).toBeEnabled();
  await page.getByRole('button',{name:'Verify email',exact:true}).click();
  await expect(page.getByRole('status')).toHaveText('Your email address is confirmed. You can now sign in.');
  await page.getByRole('main').getByRole('link',{name:'Sign in',exact:true}).click();
  await page.getByLabel('Email',{exact:true}).fill(email);await page.getByLabel('Password').fill('Browser-password-321!');
  const login=page.waitForResponse(r=>r.url().endsWith('/v1/auth/sessions')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();
  expect((await login).status()).toBe(200);
  await expect(page).toHaveURL(/account/);await expect(page.getByText(email,{exact:true})).toBeVisible();
  await expect(page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'My account'})).toBeVisible();
  await expect(page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Sign in',exact:true})).toHaveCount(0);
  await page.reload();await expect(page.getByText(email,{exact:true})).toBeVisible();
  const rolesSaved=page.waitForResponse(r=>r.url().endsWith('/v1/me/roles')&&r.request().method()==='POST');
  await page.getByRole('checkbox',{name:'Tutor',exact:true}).check();expect((await rolesSaved).status()).toBe(200);
  await page.reload();await expect(page.getByRole('checkbox',{name:'Tutor',exact:true})).toBeChecked();
  const browser=page.context().browser()!;
  const other=await browser.newContext();const device=await other.newPage();
  try {
    await device.goto(origin+'/auth/signin');
    await device.getByLabel('Email',{exact:true}).fill(email);await device.getByLabel('Password',{exact:true}).fill('Browser-password-321!');
    const secondLogin=device.waitForResponse(r=>r.url().endsWith('/v1/auth/sessions')&&r.request().method()==='POST');
    await device.getByRole('button',{name:'Sign in',exact:true}).click();expect((await secondLogin).status()).toBe(200);
    await expect(device.getByText(email,{exact:true})).toBeVisible();
    await page.reload();
    const revoked=page.waitForResponse(r=>r.url().endsWith('/v1/auth/sessions/others')&&r.request().method()==='DELETE');
    await page.getByRole('button',{name:'Sign out other sessions',exact:true}).click();expect((await revoked).status()).toBe(204);
    await expect(page.getByRole('button',{name:'Sign out other sessions',exact:true})).toBeDisabled();
    await device.reload();await expect(device).toHaveURL(/signin/);
  } finally {await other.close();}
  await page.getByRole('button',{name:'Sign out',exact:true}).click();await expect(page).toHaveURL(/signin/);
  await expect(page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'Sign in',exact:true})).toBeVisible();
  await expect(page.getByRole('navigation',{name:'Main navigation'}).getByRole('link',{name:'My account'})).toHaveCount(0);
  await page.goto('/account');await expect(page).toHaveURL(/signin/);
  await page.getByRole('link',{name:'Forgot password?'}).click();
  await expect(page.getByRole('heading',{name:'Reset your password',exact:true})).toBeVisible();
  await page.getByLabel('Email',{exact:true}).fill(email);await page.getByRole('button',{name:'Send reset link',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('If this email belongs to an eligible account');
  await page.getByRole('link',{name:'Open captured email inbox'}).click();
  await page.getByRole('listitem').filter({hasText:email}).getByRole('link',{name:'Open password reset link'}).click();
  await page.getByLabel('New password').fill('Updated-browser-password-456!');await page.getByRole('button',{name:'Update password',exact:true}).click();
  await expect(page.getByRole('status')).toContainText('All sessions have been signed out.');
  await page.getByRole('main').getByRole('link',{name:'Sign in',exact:true}).click();
  await page.getByLabel('Email',{exact:true}).fill(email);await page.getByLabel('Password',{exact:true}).fill('Updated-browser-password-456!');
  const updatedLogin=page.waitForResponse(r=>r.url().endsWith('/v1/auth/sessions')&&r.request().method()==='POST');
  await page.getByRole('button',{name:'Sign in',exact:true}).click();expect((await updatedLogin).status()).toBe(200);
  await expect(page.getByText(email,{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Sign out',exact:true}).click();await expect(page).toHaveURL(/signin/);
});
